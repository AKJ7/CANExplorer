def find_iscc() -> str:
    candidates = [shutil.which('iscc'), shutil.which('ISCC')]
    for variable in ('ProgramFiles(x86)', 'ProgramFiles', 'LOCALAPPDATA'):
        if os.environ.get(variable):
            candidates.append(str(Path(os.environ[variable]) / 'Inno Setup 6' / 'ISCC.exe'))
            candidates.append(str(Path(os.environ[variable]) / 'Programs' / 'Inno Setup 6' / 'ISCC.exe'))
    for candidate in candidates:
        if candidate and Path(candidate).exists():
            return candidate
    raise SystemExit('Inno Setup 6 (ISCC.exe) not found; install it, e.g. with "choco install innosetup"')


def windows_setup(bundle: Path) -> Path:
    script = DIST / 'canexplorer.iss'
    script.write_text(inno_setup_script(bundle, OUTPUT), encoding='utf-8')
    run([find_iscc(), '/Q', script])
    return OUTPUT / f'{base_name("windows")}-setup.exe'


# macOS


def macos_dmg(bundle: Path) -> Path:
    target = OUTPUT / f'{base_name("macos")}.dmg'
    target.unlink(missing_ok=True)
    with tempfile.TemporaryDirectory() as staging:
        staging = Path(staging)
        run(['ditto', bundle, staging / bundle.name])  # Keeps symlinks, permissions and extended attributes
        (staging / 'Applications').symlink_to('/Applications')
        run(
            [
                'hdiutil',
                'create',
                '-volname',
                NAME,
                '-srcfolder',
                staging,
                '-fs',
                'HFS+',
                '-format',
                'UDZO',
                '-ov',
                target,
            ]
        )
    return target


# Linux


def _install_icons(share: Path) -> None:
    for size in ICON_SIZES:
        icon = share / 'icons' / 'hicolor' / f'{size}x{size}' / 'apps' / f'{APP_ID}.png'
        icon.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(APP_ICONS / f'{size}.png', icon)


def _copy_bundle(bundle: Path, destination: Path) -> None:
    shutil.copytree(bundle, destination, symlinks=True)
    executable = destination / NAME
    executable.chmod(executable.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _normalise_permissions(root: Path) -> None:
    """755 for directories and executables, 644 for other files, whatever the umask of the build was."""
    for path in [root, *root.rglob('*')]:
        if path.is_symlink():
            continue
        if path.is_dir() or path.stat().st_mode & stat.S_IXUSR:
            path.chmod(0o755)
        else:
            path.chmod(0o644)


def appimagetool() -> Path:
    tool = shutil.which('appimagetool')
    if tool:
        return Path(tool)
    path = ROOT / 'build' / f'appimagetool-{machine()}.AppImage'
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = APPIMAGETOOL_URL.format(arch=machine())
        print(f'Downloading {url}', flush=True)
        urllib.request.urlretrieve(url, path)
    path.chmod(0o755)
    return path


def linux_appimage(bundle: Path) -> Path:
    target = OUTPUT / f'{base_name("linux")}.AppImage'
    with tempfile.TemporaryDirectory() as directory:
        appdir = Path(directory) / f'{NAME}.AppDir'
        _copy_bundle(bundle, appdir / 'usr' / 'lib' / 'canexplorer')
        apprun = appdir / 'AppRun'
        apprun.write_text(
            '#!/bin/sh\n' 'HERE="$(dirname "$(readlink -f "$0")")"\n' f'exec "$HERE/usr/lib/canexplorer/{NAME}" "$@"\n'
        )
        apprun.chmod(0o755)
        (appdir / f'{APP_ID}.desktop').write_text(desktop_entry([NAME]))
        _install_icons(appdir / 'usr' / 'share')
        shutil.copy2(APP_ICONS / '256.png', appdir / f'{APP_ID}.png')
        (appdir / '.DirIcon').symlink_to(f'{APP_ID}.png')
        _normalise_permissions(appdir)
        # Without FUSE (containers, CI runners) the tool runs extracted
        environment = dict(os.environ, ARCH=machine(), APPIMAGE_EXTRACT_AND_RUN='1')
        run([appimagetool(), '--no-appstream', appdir, target], env=environment)
    return target


def linux_deb(bundle: Path) -> Path:
    arch = {'x86_64': 'amd64', 'aarch64': 'arm64'}.get(machine(), machine())
    target = OUTPUT / f'{base_name("linux")}.deb'
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory) / 'package'
        _copy_bundle(bundle, root / 'opt' / 'canexplorer')
        binary = root / 'usr' / 'bin' / 'canexplorer'
        binary.parent.mkdir(parents=True)
        binary.symlink_to(f'/opt/canexplorer/{NAME}')
        applications = root / 'usr' / 'share' / 'applications'
        applications.mkdir(parents=True)
        (applications / f'{APP_ID}.desktop').write_text(desktop_entry(['/opt/canexplorer/' + NAME]))
        _install_icons(root / 'usr' / 'share')
        size = sum(path.stat().st_size for path in root.rglob('*') if path.is_file() and not path.is_symlink())
        control = root / 'DEBIAN' / 'control'
        control.parent.mkdir()
        control.write_text(
            f'Package: canexplorer\n'
            f'Version: {app_version()}\n'
            f'Section: electronics\n'
            f'Priority: optional\n'
            f'Architecture: {arch}\n'
            f'Maintainer: {PUBLISHER} <akj123429@gmail.com>\n'
            f'Installed-Size: {size // 1024}\n'
            f'Depends: libc6, libegl1, libgl1, libxkbcommon0, libxkbcommon-x11-0, libxcb-cursor0, libfontconfig1, libdbus-1-3\n'
            f'Homepage: {HOMEPAGE}\n'
            f'Description: CAN, CAN FD and LIN bus monitor\n'
            f' {DESCRIPTION}, with signal databases, recording and replay, UDS\n'
            f' diagnostics, J1939 and CANopen tools, simulation and test automation.\n'
        )
        for script, command in (
            ('postinst', 'update-desktop-database -q /usr/share/applications || true\n'),
            ('postrm', 'update-desktop-database -q /usr/share/applications || true\n'),
        ):
            path = control.parent / script
            path.write_text('#!/bin/sh\nset -e\n' + command)
            path.chmod(0o755)
        _normalise_permissions(root)
        run(['dpkg-deb', '--root-owner-group', '--build', root, target])
    return target


BUILDERS = {'setup': windows_setup, 'dmg': macos_dmg, 'appimage': linux_appimage, 'deb': linux_deb}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    available = FORMATS.get(sys.platform, ())
    parser.add_argument('--formats', nargs='+', choices=sorted(BUILDERS), default=list(available))
    parser.add_argument('--bundle', type=Path, help='the bundle (default: dist/CANExplorer, or .app on macOS)')
    args = parser.parse_args()
    bundle = args.bundle or DIST / (f'{NAME}.app' if sys.platform == 'darwin' else NAME)
    if not bundle.exists():
        raise SystemExit(f'Bundle not found: {bundle}; build it first with packaging/build.py')
    unsupported = [name for name in args.formats if name not in available]
    if unsupported:
        parser.error(f'{", ".join(unsupported)} cannot be built on {sys.platform}')
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name in args.formats:
        installer = BUILDERS[name](bundle.resolve())
        if not installer.exists():
            raise SystemExit(f'Expected installer not found: {installer}')
        print(f'Installer: {installer} ({installer.stat().st_size / 1e6:.1f} MB)', flush=True)


if __name__ == '__main__':
    main()
