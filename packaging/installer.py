"""Create installers from the bundle built by packaging/build.py.

Usage: uv run python packaging/installer.py [--formats FORMAT ...]

| Platform | Formats (default: all of the platform) | Needs |
|---|---|---|
| Windows | setup: an Inno Setup installer (.exe) | Inno Setup 6 (`choco install innosetup`) |
| macOS | dmg: a disk image with the app and a link to Applications | hdiutil (part of macOS) |
| Linux | appimage: a portable AppImage; deb: a Debian/Ubuntu package | appimagetool (downloaded); dpkg-deb |

The installers are written to dist/installers, named CANExplorer-<version>-<platform>-<arch>.<extension>.
"""

import argparse
import os
import platform
import shutil
import stat
import subprocess
import sys
import tempfile
import urllib.request
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from can_explorer.desktop import APP_ID, ICON_SIZES, desktop_entry  # noqa: E402

DIST = ROOT / 'dist'
OUTPUT = DIST / 'installers'
NAME = 'CANExplorer'
DISTRIBUTION = 'can-explorer'
PUBLISHER = 'AKJ7'
HOMEPAGE = 'https://github.com/AKJ7/CANExplorer'
DESCRIPTION = 'Monitor, analyse, diagnose and simulate CAN, CAN FD and LIN buses'
ICONS = ROOT / 'packaging' / 'icons'
APP_ICONS = ROOT / 'can_explorer' / 'resources' / 'icons'  # <size>.png
APPIMAGETOOL_URL = 'https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-{arch}.AppImage'
# A fixed identifier: Windows recognises upgrades of the same application by it
WINDOWS_APP_ID = '{8F3B6C2E-5D1A-4E7B-9C4F-2A6D8E1B3C70}'
FORMATS = {'win32': ('setup',), 'darwin': ('dmg',), 'linux': ('appimage', 'deb')}


def app_version() -> str:
    return version(DISTRIBUTION)


def machine() -> str:
    return {'amd64': 'x86_64', 'arm64': 'arm64', 'aarch64': 'aarch64'}.get(
        platform.machine().lower(), platform.machine()
    )


def base_name(system: str) -> str:
    return f'{NAME}-{app_version()}-{system}-{machine()}'


def run(command, **kwargs) -> None:
    print('$', ' '.join(str(part) for part in command), flush=True)
    subprocess.run([str(part) for part in command], check=True, **kwargs)


# Windows


