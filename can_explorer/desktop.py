"""Desktop integration on Linux: a launcher (.desktop entry) with the application icon in the user's menu.

Windows and macOS take the icon from the bundle built by packaging/build.py, so nothing is installed there.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Optional

from can_explorer.sys.log_handler import get_logger

logger = get_logger(__name__)

APP_ID = 'io.github.akj7.CANExplorer'
ICONS = Path(__file__).resolve().parent / 'resources' / 'icons'  # <size>.png, generated by tools/make_icons.py
ICON_SIZES = (16, 32, 48, 64, 128, 256, 512)


def data_home() -> Path:
    return Path(os.environ.get('XDG_DATA_HOME') or Path.home() / '.local' / 'share')


def launch_command() -> List[str]:
    """How the desktop entry starts the application."""
    if '__compiled__' in globals():  # Nuitka: sys.executable may be inside the onefile's temporary folder
        return [str(Path(sys.argv[0]).resolve())]
    if getattr(sys, 'frozen', False):  # PyInstaller
        return [sys.executable]
    # Console script of the environment (uv sync, pip install)
    script = Path(sys.executable).with_name('canexplorer.exe' if sys.platform == 'win32' else 'canexplorer')
    if script.exists():
        return [str(script)]
    return [sys.executable, '-m', 'can_explorer']


def _quote(argument: str) -> str:
    if any(character in argument for character in ' \t"\'\\$`'):
        return '"' + argument.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('`', '\\`') + '"'
    return argument


def desktop_entry(command: List[str]) -> str:
    return '\n'.join(
        [
            '[Desktop Entry]',
            'Type=Application',
            'Name=CANExplorer',
            'GenericName=CAN Bus Monitor',
            'Comment=Monitor, analyse, diagnose and simulate CAN, CAN FD and LIN buses',
            f'Exec={" ".join(_quote(argument) for argument in command)}',
            f'Icon={APP_ID}',
            'Terminal=false',
            'Categories=Development;Electronics;Engineering;',
            'Keywords=CAN;CAN FD;LIN;bus;automotive;UDS;DBC;',
            f'StartupWMClass={APP_ID}',
            '',
        ]
    )


def _paths(base: Path) -> List[Path]:
    paths = [base / 'applications' / f'{APP_ID}.desktop']
    paths += [base / 'icons' / 'hicolor' / f'{size}x{size}' / 'apps' / f'{APP_ID}.png' for size in ICON_SIZES]
    return paths


def _update_caches(base: Path) -> None:
    """Best effort: desktops also notice the files without these tools, only later."""
    for command in (
        ['update-desktop-database', str(base / 'applications')],
        ['gtk-update-icon-cache', '--quiet', '--ignore-theme-index', str(base / 'icons' / 'hicolor')],
    ):
        if shutil.which(command[0]):
            subprocess.run(command, check=False, capture_output=True, timeout=30)


def install(base: Optional[Path] = None, command: Optional[List[str]] = None, update_caches: bool = True) -> Path:
    """Install the desktop entry and icons for the current user. Returns the desktop entry's path."""
    base = base or data_home()
    entry, *icons = _paths(base)
    for size, icon in zip(ICON_SIZES, icons, strict=True):
        icon.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ICONS / f'{size}.png', icon)
    entry.parent.mkdir(parents=True, exist_ok=True)
    entry.write_text(desktop_entry(command or launch_command()), encoding='utf-8')
    entry.chmod(0o755)
    if update_caches:
        _update_caches(base)
    return entry


def uninstall(base: Optional[Path] = None, update_caches: bool = True) -> List[Path]:
    """Remove the desktop entry and icons. Returns the removed files."""
    base = base or data_home()
    removed = [path for path in _paths(base) if path.exists()]
    for path in removed:
        path.unlink()
    if removed and update_caches:
        _update_caches(base)
    return removed


def run(argument: str) -> int:
    """Handle --install-desktop-entry and --uninstall-desktop-entry."""
    if not sys.platform.startswith('linux'):
        print('Only needed on Linux; on Windows and macOS the application bundle carries the icon.')
        return 0
    if argument == '--install-desktop-entry':
        print(f'Installed {install()}')
    else:
        removed = uninstall()
        print('\n'.join(f'Removed {path}' for path in removed) or 'Nothing to remove')
    return 0
